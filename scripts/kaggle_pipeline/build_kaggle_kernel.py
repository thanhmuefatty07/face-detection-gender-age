def _ensure_all_splits_covered_df(df, shards_dir: Path | None = None):
    if df.empty or "split" not in df.columns or "subject_id" not in df.columns:
        return df
    try:
        from src.mining.curation import ExtremeDatasetCurator

        df = ExtremeDatasetCurator._propagate_subject_gender(df, shards_dir=None)
        df = ExtremeDatasetCurator._ensure_all_splits_covered(df, shards_dir=None)
        df = ExtremeDatasetCurator._calibrate_demographic_sample_weights(df, shards_dir=shards_dir)
        ExtremeDatasetCurator._sync_shards_with_master(df, shards_dir)
        return df
    except Exception:
        pass
    present = set(df["split"].dropna().unique())
    required = {"train", "val", "test"}
    if present == required:
        return df
    known_mask = df["subject_id"].notna() & df["subject_id"].astype(str).str.strip().ne("")
    known_subjects = sorted(df.loc[known_mask, "subject_id"].astype(str).unique())
    if len(known_subjects) < 3:
        return df
    df = df.copy()
    subj_splits = {s: df.loc[df["subject_id"] == s, "split"].iloc[0] for s in known_subjects}
    for missing_split in ("train", "val", "test"):
        if missing_split not in set(df["split"].dropna().unique()):
            counts = df.loc[known_mask, "split"].value_counts().to_dict()
            donor_split = max(counts, key=lambda k: counts[k])
            candidates = [s for s, sp in subj_splits.items() if sp == donor_split]
            if len(candidates) > 1:
                chosen = candidates[-1]
                subj_splits[chosen] = missing_split
                df.loc[df["subject_id"] == chosen, "split"] = missing_split
    if shards_dir is not None and shards_dir.exists() and "sha256" in df.columns:
        import pandas as pd
        split_map = dict(zip(df["sha256"], df["split"]))
        for sm in sorted(shards_dir.glob("shard_*_manifest.parquet")):
            try:
                sdf = pd.read_parquet(sm)
                if "sha256" in sdf.columns and "split" in sdf.columns:
                    sdf["split"] = sdf["sha256"].map(split_map).fillna(sdf["split"])
                    sdf.to_parquet(str(sm), index=False)
            except Exception:
                pass
    return df


def ensure_master_manifest(golden_dataset_dir: Path | str):
    """
    Consolidates all shard manifests (shards/shard_*_manifest.parquet) into root metadata.parquet and metadata.csv.
    Self-healing: Reconstructs master manifest from individual shard checkpoints if session was interrupted.
    """
    import pandas as pd
    golden_dir = Path(golden_dataset_dir)
    p_parquet = golden_dir / "metadata.parquet"
    p_csv = golden_dir / "metadata.csv"
    shards_dir = golden_dir / "shards"
    shard_manifests = sorted(shards_dir.glob("shard_*_manifest.parquet")) if shards_dir.exists() else []

    if shard_manifests:
        print(f"[Manifest] Consolidating {len(shard_manifests)} shard manifest(s) from {shards_dir} ...")
        dfs = []
        for sm in shard_manifests:
            try:
                dfs.append(pd.read_parquet(sm))
            except Exception as e:
                print(f"⚠️ Warning reading shard manifest {sm}: {e}")
        if dfs:
            master = pd.concat(dfs, ignore_index=True)
            if "sha256" in master.columns:
                master.drop_duplicates(subset=["sha256"], inplace=True, ignore_index=True)
            master = _ensure_all_splits_covered_df(master, shards_dir=shards_dir)
            master.to_parquet(str(p_parquet), index=False)
            csv_safe_manifest(master).to_csv(str(p_csv), index=False)
            print(f"✅ Consolidated {len(master)} records across {len(shard_manifests)} shards into {p_parquet} and {p_csv}")
            return master

    if p_parquet.exists():
        try:
            return pd.read_parquet(p_parquet)
        except Exception:
            pass

    empty_df = pd.DataFrame()
    golden_dir.mkdir(parents=True, exist_ok=True)
    empty_df.to_parquet(str(p_parquet), index=False)
    empty_df.to_csv(str(p_csv), index=False)
    return empty_df


